using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.Text;

namespace Gener8;

internal static class SourceProducer
{
    public static void Emit(SourceProductionContext context, ClassTarget target)
    {
        EmitModel(context, target);
        EmitExtensions(context, target);
        if (target.Repository != RepositoryKind.None)
            EmitRepository(context, target);
    }

    private static void EmitModel(SourceProductionContext context, ClassTarget target)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        var indent = "";
        if (target.Namespace is not null)
        {
            sb.AppendLine($"namespace {target.Namespace}");
            sb.AppendLine("{");
            indent = "    ";
        }

        sb.AppendLine($"{indent}{target.Accessibility} partial class {target.ClassName}");
        sb.AppendLine($"{indent}{{");

        foreach (var prop in target.Properties)
        {
            var accessors = new StringBuilder(" {");
            if (prop.HasGetter) accessors.Append(" get;");
            if (prop.IsInitOnly) accessors.Append(" init;");
            else if (prop.HasSetter) accessors.Append(" set;");
            accessors.Append(" }");

            var modifier = prop.IsRequired ? "required " : "";
            var line = $"{indent}    public {modifier}{prop.Type} {prop.Name}{accessors}";
            if (prop.Initializer is not null)
                line += $" = {prop.Initializer};";
            sb.AppendLine(line);
        }

        sb.AppendLine($"{indent}}}");

        if (target.Namespace is not null)
            sb.AppendLine("}");

        var hintName = target.Namespace is not null
            ? $"{target.Namespace}.{target.ClassName}.g.cs"
            : $"{target.ClassName}.g.cs";

        context.AddSource(hintName, SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void EmitExtensions(SourceProductionContext context, ClassTarget target)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        var indent = "";
        if (target.Namespace is not null)
        {
            sb.AppendLine($"namespace {target.Namespace}");
            sb.AppendLine("{");
            indent = "    ";
        }

        var extAccessibility = target.Accessibility == "public" ? "public" : "internal";
        sb.AppendLine($"{indent}{extAccessibility} static class {target.ClassName}Extensions");
        sb.AppendLine($"{indent}{{");

        // ToModel: dto → model
        sb.AppendLine($"{indent}    public static {target.ModelFullName} ToModel(this {target.ClassName} dto)");
        sb.AppendLine($"{indent}    {{");
        sb.AppendLine($"{indent}        return new {target.ModelFullName}");
        sb.AppendLine($"{indent}        {{");
        foreach (var prop in target.Properties)
        {
            if (prop.FlattenedReadPath is not null) continue;
            if (!prop.HasGetter) continue;
            if (!prop.HasSetter && !prop.IsInitOnly) continue;
            var modelPropName = prop.ModelPropertyName ?? prop.Name;
            var nc = prop.Type.EndsWith("?") ? "?" : "";
            var dtoRead = prop.HasTypeMapping
                ? $"dto.{prop.Name}{nc}.ToModel()"
                : $"dto.{prop.Name}";
            sb.AppendLine($"{indent}            {modelPropName} = {dtoRead},");
        }
        sb.AppendLine($"{indent}        }};");
        sb.AppendLine($"{indent}    }}");
        sb.AppendLine();

        // ToDto: model → dto
        sb.AppendLine($"{indent}    public static {target.ClassName} ToDto(this {target.ModelFullName} model)");
        sb.AppendLine($"{indent}    {{");
        sb.AppendLine($"{indent}        return new {target.ClassName}");
        sb.AppendLine($"{indent}        {{");
        foreach (var prop in target.Properties)
        {
            if (!prop.HasSetter && !prop.IsInitOnly) continue;
            string rhs;
            if (prop.FlattenedReadPath is not null)
            {
                if (prop.HasTypeMapping) continue;  // flattened + type-mapped: skip, cannot chain
                rhs = $"model.{prop.FlattenedReadPath}";
            }
            else
            {
                var modelPropName = prop.ModelPropertyName ?? prop.Name;
                var nc = prop.Type.EndsWith("?") ? "?" : "";
                rhs = prop.HasTypeMapping
                    ? $"model.{modelPropName}{nc}.ToDto()"
                    : $"model.{modelPropName}";
            }
            sb.AppendLine($"{indent}            {prop.Name} = {rhs},");
        }
        sb.AppendLine($"{indent}        }};");
        sb.AppendLine($"{indent}    }}");

        sb.AppendLine($"{indent}}}");

        if (target.Namespace is not null)
            sb.AppendLine("}");

        var hintName = target.Namespace is not null
            ? $"{target.Namespace}.{target.ClassName}Extensions.g.cs"
            : $"{target.ClassName}Extensions.g.cs";

        context.AddSource(hintName, SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void EmitRepository(SourceProductionContext context, ClassTarget target)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        var indent = "";
        if (target.Namespace is not null)
        {
            sb.AppendLine($"namespace {target.Namespace}");
            sb.AppendLine("{");
            indent = "    ";
        }

        var className = target.ClassName;

        if (target.Repository == RepositoryKind.DynamoDb)
        {
            var repoClassName = $"{className}DynamoDbRepository";
            sb.AppendLine($"{indent}{target.Accessibility} class {repoClassName} : global::Gener8.Repository<{className}>");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{indent}    private readonly global::Amazon.DynamoDBv2.IAmazonDynamoDB _client;");
            sb.AppendLine($"{indent}    private readonly global::Gener8.DynamoDbRepositorySettings _settings;");
            sb.AppendLine();
            sb.AppendLine($"{indent}    public {repoClassName}(global::Amazon.DynamoDBv2.IAmazonDynamoDB client, global::Gener8.DynamoDbRepositorySettings settings)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        _client = client;");
            sb.AppendLine($"{indent}        _settings = settings;");
            sb.AppendLine($"{indent}    }}");
        }
        else
        {
            var repoClassName = $"{className}MongoDbRepository";
            sb.AppendLine($"{indent}{target.Accessibility} class {repoClassName} : global::Gener8.Repository<{className}>");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{indent}    private readonly global::MongoDB.Driver.IMongoCollection<{className}> _collection;");
            sb.AppendLine();
            sb.AppendLine($"{indent}    public {repoClassName}(global::MongoDB.Driver.IMongoClient client, global::Gener8.MongoDbRepositorySettings settings)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        _collection = client.GetDatabase(settings.DatabaseName).GetCollection<{className}>(settings.CollectionName);");
            sb.AppendLine($"{indent}    }}");
        }

        sb.AppendLine();
        EmitRepositoryMethodStubs(sb, indent, className);
        sb.AppendLine($"{indent}}}");

        if (target.Namespace is not null)
            sb.AppendLine("}");

        var suffix = target.Repository == RepositoryKind.DynamoDb ? "DynamoDb" : "MongoDb";
        var hintName = target.Namespace is not null
            ? $"{target.Namespace}.{className}{suffix}Repository.g.cs"
            : $"{className}{suffix}Repository.g.cs";

        context.AddSource(hintName, SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void EmitRepositoryMethodStubs(StringBuilder sb, string indent, string className)
    {
        sb.AppendLine($"{indent}    public override global::System.Threading.Tasks.Task<{className}?> GetByIdAsync(string id, global::System.Threading.CancellationToken cancellationToken = default)");
        sb.AppendLine($"{indent}        => throw new global::System.NotImplementedException();");
        sb.AppendLine();
        sb.AppendLine($"{indent}    public override global::System.Threading.Tasks.Task<global::System.Collections.Generic.IEnumerable<{className}>> GetAllAsync(global::System.Threading.CancellationToken cancellationToken = default)");
        sb.AppendLine($"{indent}        => throw new global::System.NotImplementedException();");
        sb.AppendLine();
        sb.AppendLine($"{indent}    public override global::System.Threading.Tasks.Task SaveAsync({className} entity, global::System.Threading.CancellationToken cancellationToken = default)");
        sb.AppendLine($"{indent}        => throw new global::System.NotImplementedException();");
        sb.AppendLine();
        sb.AppendLine($"{indent}    public override global::System.Threading.Tasks.Task DeleteAsync(string id, global::System.Threading.CancellationToken cancellationToken = default)");
        sb.AppendLine($"{indent}        => throw new global::System.NotImplementedException();");
    }
}
